pub type Signature = [u8; 64];

/// Negated compressed base point (-G). Identical to G with the sign bit
/// (bit 7 of the last byte) flipped. Used so that the signature check
/// `R == sB - kA` can be rewritten as a single multiscalar multiplication:
/// `msm([s, k], [-G, A]) == -R`.
const NEG_G: [u8; 32] = [
    88, 102, 102, 102, 102, 102, 102, 102, 102, 102, 102, 102, 102, 102, 102, 102, 102, 102, 102,
    102, 102, 102, 102, 102, 102, 102, 102, 102, 102, 102, 102, 230,
];

/// The hash implementation used by [`verify`]: the `sol_sha512` syscall
/// (SIMD-0512) on Solana targets, the in-program `FastSha512` when the
/// `fast-sha512` feature opts out of the syscall, and the software `sha2`
/// implementation on host builds.
#[cfg(all(
    any(target_arch = "bpf", target_os = "solana"),
    not(feature = "fast-sha512")
))]
type DefaultHasher = crate::hasher::Sha512Syscall;
#[cfg(all(
    any(target_arch = "bpf", target_os = "solana"),
    feature = "fast-sha512"
))]
type DefaultHasher = crate::hasher::FastSha512;
#[cfg(not(any(target_arch = "bpf", target_os = "solana")))]
type DefaultHasher = crate::hasher::Sha512;

/// Verify an ed25519 signature over a vectored message.
///
/// Point encodings are validated according to RFC 8032. This uses the
/// RFC-permitted cofactorless verification equation, so canonical small-order
/// points are not rejected. Use [`verify_strict`] when that additional check
/// is required.
///
/// On Solana targets the challenge hash `H(R || A || M)` is computed via the
/// `sol_sha512` syscall
/// ([SIMD-0512](https://github.com/solana-foundation/solana-improvement-documents/blob/main/proposals/0512-sha512-syscall.md)),
/// which requires the `enable_sha512_syscall` feature gate
/// (`s512oDwgx8hjMnaQjXfqqrZroVj4HvC6TkN3iSSWXCh`) to be active on the
/// target cluster. On clusters without the gate (or other SVM runtimes
/// without the syscall), build with the `fast-sha512` feature to hash
/// in-program instead. Host builds always hash in software.
#[inline(always)]
pub fn verify(pubkey: &Address, sig: &Signature, messages: &[&[u8]]) -> Result<(), ProgramError> {
    verify_with_hasher::<DefaultHasher>(pubkey, sig, messages)
}

/// Strictly verify an ed25519 signature, rejecting small-order public keys and
/// `R` values. This matches the Solana ed25519 precompile's point checks.
#[inline(always)]
pub fn verify_strict(
    pubkey: &Address,
    sig: &Signature,
    messages: &[&[u8]],
) -> Result<(), ProgramError> {
    verify_with_hasher_strict::<DefaultHasher>(pubkey, sig, messages)
}

/// Verify a signature using the provided hash implementation and RFC 8032
/// point decoding rules, without additional small-order rejection.
#[inline(always)]
pub fn verify_with_hasher<H: Hasher>(
    pubkey: &Address,
    sig: &Signature,
    messages: &[&[u8]],
) -> Result<(), ProgramError> {
    // SAFETY: first 32 bytes of [u8; 64] is a valid [u8; 32].
    let sig_r: &[u8; 32] = unsafe { &*(sig.as_ptr() as *const [u8; 32]) };
    // SAFETY: Address is #[repr(transparent)] over [u8; 32].
    let pubkey_bytes: &[u8; 32] = unsafe { &*(pubkey as *const Address as *const [u8; 32]) };

    validate_point_encodings(pubkey_bytes, sig_r)?;

    let challenge = challenge::<H>(sig_r, pubkey, messages);

    verify_prehashed_unchecked(pubkey, sig, &challenge)
}

/// Strictly verify a signature using the provided hash implementation.
#[inline(always)]
pub fn verify_with_hasher_strict<H: Hasher>(
    pubkey: &Address,
    sig: &Signature,
    messages: &[&[u8]],
) -> Result<(), ProgramError> {
    // SAFETY: first 32 bytes of [u8; 64] is a valid [u8; 32].
    let sig_r: &[u8; 32] = unsafe { &*(sig.as_ptr() as *const [u8; 32]) };
    // SAFETY: Address is #[repr(transparent)] over [u8; 32].
    let pubkey_bytes: &[u8; 32] = unsafe { &*(pubkey as *const Address as *const [u8; 32]) };

    validate_points_strict(pubkey_bytes, sig_r)?;

    let challenge = challenge::<H>(sig_r, pubkey, messages);

    verify_prehashed_unchecked(pubkey, sig, &challenge)
}

/// Verify an ed25519 signature using a precomputed challenge hash `H(R || A || M)`.
/// This is useful in cases where the challenge hash needs to be computed off-chain
/// or pre-computed on-chain for efficiency reasons.
/// Point encodings are validated according to RFC 8032. Use
/// [`verify_prehashed_strict`] when canonical small-order points must also be
/// rejected.
///
/// # Safety (validation delegated to the MSM syscall)
///
/// The following checks are intentionally omitted because the Solana
/// `sol_curve_multiscalar_mul` syscall already performs them internally
/// (see `agave/curves/curve25519/src/edwards.rs` and `scalar.rs`):
///
/// - **Point decompression / on-curve check** for both `pubkey` and the
///   constant `-G`: the syscall calls `CompressedEdwardsY::decompress()`
///   on every point and returns failure if decompression fails.
/// - **Scalar canonicality** of `s` (the upper half of the signature):
///   the syscall calls `Scalar::from_canonical_bytes()` on every scalar
///   and returns failure if the scalar is non-canonical.
///
/// If any of those checks fail the MSM returns `None`, which we map to
/// `ProgramError::InvalidArgument`.
#[inline(always)]
#[allow(non_snake_case)]
pub fn verify_prehashed(
    pubkey: &Address,
    sig: &Signature,
    challenge: &[u8; 64],
) -> Result<(), ProgramError> {
    // SAFETY: first 32 bytes of [u8; 64] is a valid [u8; 32].
    let sig_r: &[u8; 32] = unsafe { &*(sig.as_ptr() as *const [u8; 32]) };
    // SAFETY: Address is #[repr(transparent)] over [u8; 32].
    let pubkey_bytes: &[u8; 32] = unsafe { &*(pubkey as *const Address as *const [u8; 32]) };

    validate_point_encodings(pubkey_bytes, sig_r)?;
    verify_prehashed_unchecked(pubkey, sig, challenge)
}

#[inline(always)]
#[allow(non_snake_case)]
fn verify_prehashed_unchecked(
    pubkey: &Address,
    sig: &Signature,
    challenge: &[u8; 64],
) -> Result<(), ProgramError> {
    // SAFETY: [u8; 64] has the same layout as [[u8; 32]; 2].
    let (sig_r, sig_s): &([u8; 32], [u8; 32]) = unsafe { &*(sig as *const [u8; 64] as *const _) };

    // SAFETY: Address is #[repr(transparent)] over [u8; 32].
    let pubkey_bytes: &[u8; 32] = unsafe { &*(pubkey as *const Address as *const [u8; 32]) };

    // Build the [[u8; 32]; 2] scalar array in place so that the reduced `k`
    // limbs can be written straight into the MSM input slot instead of
    // materializing through a separate 32-byte stack temporary.
    let mut scalars: [[u8; 32]; 2] = [*sig_s, [0u8; 32]];
    scalar_from_bytes_mod_order_wide_into(challenge, &mut scalars[1]);

    let points = [NEG_G, *pubkey_bytes];

    // msm([s, k], [-G, A]) = s*(-G) + k*A = k*A - s*G = -(s*G - k*A) = -R
    let neg_R =
        multiscalar_multiply_edwards(&scalars, &points).ok_or(ProgramError::InvalidArgument)?;

    // Negate sig_R (flip sign bit) to compare against -R.
    let mut neg_sig_R = *sig_r;
    neg_sig_R[31] ^= 0x80;

    if neg_R == neg_sig_R {
        Ok(())
    } else {
        Err(ProgramError::InvalidArgument)
    }
}

/// Strictly verify a signature using a precomputed challenge hash.
#[inline(always)]
#[allow(non_snake_case)]
pub fn verify_prehashed_strict(
    pubkey: &Address,
    sig: &Signature,
    challenge: &[u8; 64],
) -> Result<(), ProgramError> {
    // SAFETY: first 32 bytes of [u8; 64] is a valid [u8; 32].
    let sig_r: &[u8; 32] = unsafe { &*(sig.as_ptr() as *const [u8; 32]) };
    // SAFETY: Address is #[repr(transparent)] over [u8; 32].
    let pubkey_bytes: &[u8; 32] = unsafe { &*(pubkey as *const Address as *const [u8; 32]) };

    validate_points_strict(pubkey_bytes, sig_r)?;
    verify_prehashed_unchecked(pubkey, sig, challenge)
}

#[inline(always)]
fn challenge<H: Hasher>(sig_r: &[u8; 32], pubkey: &Address, messagev: &[&[u8]]) -> [u8; 64] {
    let mut hasher = H::new();
    hasher.update(sig_r);
    hasher.update(pubkey.as_ref());

    for message in messagev {
        hasher.update(message);
    }

    hasher.finalize()
}

